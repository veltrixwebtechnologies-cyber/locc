/** Map of brandId to BrandCatalogProduct[] */
export const BRAND_PRODUCTS_BY_BRAND: Record<string, BrandCatalogProduct[]> = BRAND_PRODUCTS_CATALOG.reduce(
  (acc, item) => {
    if (!acc[item.brandId]) acc[item.brandId] = [];
    acc[item.brandId].push(item);
    return acc;
  },
  {} as Record<string, BrandCatalogProduct[]>,
);

/**
 * Find brand products for a given brandId or brand name / store name.
 */
export function getBrandProducts(brandIdOrName: string): BrandCatalogProduct[] {
  const normalized = brandIdOrName.toLowerCase().trim();
  
  // 1. Direct brandId match
  if (BRAND_PRODUCTS_BY_BRAND[normalized]) {
    return BRAND_PRODUCTS_BY_BRAND[normalized];
  }

  // 2. Keyword detection
  if (normalized.includes("peter england") || normalized === "peter-england") {
    return BRAND_PRODUCTS_BY_BRAND["peter-england"] ?? [];
  }
  if (normalized.includes("raymond")) {
    return BRAND_PRODUCTS_BY_BRAND["raymond"] ?? [];
  }
  if (normalized === "max" || normalized.includes("max fashion") || /\bmax\b/i.test(normalized)) {
    return BRAND_PRODUCTS_BY_BRAND["max"] ?? [];
  }
  if (normalized.includes("trend") || normalized === "trends") {
    return BRAND_PRODUCTS_BY_BRAND["trends"] ?? [];
  }
  if (normalized.includes("allen solly") || normalized === "allen-solly") {
    return BRAND_PRODUCTS_BY_BRAND["allen-solly"] ?? [];
  }
  if (normalized.includes("louis philippe") || normalized === "louis-philippe") {
    return BRAND_PRODUCTS_BY_BRAND["louis-philippe"] ?? [];
  }
  if (normalized.includes("indian terrain") || normalized === "indian-terrain") {
    return BRAND_PRODUCTS_BY_BRAND["indian-terrain"] ?? [];
  }
  if (normalized.includes("jockey")) {
    return BRAND_PRODUCTS_BY_BRAND["jockey"] ?? [];
  }
  if (normalized.includes("bata")) {
    return BRAND_PRODUCTS_BY_BRAND["bata"] ?? [];
  }
  if (normalized.includes("woodland")) {
    return BRAND_PRODUCTS_BY_BRAND["woodland"] ?? [];
  }
  if (normalized.includes("kalyan")) {
    return BRAND_PRODUCTS_BY_BRAND["kalyan-jewellers"] ?? [];
  }
  if (normalized.includes("jos alukkas") || normalized.includes("josalukkas")) {
    return BRAND_PRODUCTS_BY_BRAND["jos-alukkas"] ?? [];
  }
  if (normalized.includes("joyalukkas") || normalized.includes("joy alukkas")) {
    return BRAND_PRODUCTS_BY_BRAND["joyalukkas"] ?? [];
  }

  return [];
}

/**
 * Retrieve a specific product by its slug or product ID.
 */
export function getBrandProductBySlug(slug: string): BrandCatalogProduct | undefined {
  const cleanSlug = slug.toLowerCase().trim();
  return BRAND_PRODUCTS_CATALOG.find((p) => p.slug === cleanSlug);
}

/**
 * Maps brand products to standard Product entities for a given store.
 */
export function getBrandCatalogProducts(
  shopId: string,
  shopName: string,
  category?: string,
): {
  id: string;
  storeId: string;
  shopName?: string;
  name: string;
  price: number;
  unit: string;
  category: string;
  stock?: number;
  imageUrl?: string;
}[] {
  const cleanId = shopId.startsWith("imported:") ? shopId.slice("imported:".length) : shopId;
  const brandStore = BRAND_STORES_CATALOG.find((s) => s.id === cleanId);
  const brandProducts = getBrandProducts(brandStore?.brandId || shopName);

  if (brandProducts.length > 0) {
    return brandProducts.map((item) => ({
      id: `sample:${shopId}:${item.slug}`,
      storeId: shopId,
      shopName,
      name: item.name,
      price: item.price,
      unit: item.unit,
      category: item.subcategory,
      stock: item.stock,
      imageUrl: item.imageUrl,
    }));
  }
  return [];
}

