import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { demoCategories, shopsPerCategory, seedTag } from "./demo-category-catalog.mjs";

const sqlString = (value) => `'${value.replaceAll("'", "''")}'`;
export function buildSeedSQL() {
  const keys = new Set(demoCategories.map(({ key }) => key));
  if (keys.size !== 13 || demoCategories.some(({ products }) => products.length !== 10)) {
    throw new Error("The demo seed requires 13 unique categories with 10 products each.");
  }
  const catalog = demoCategories.map((category) => ({
    ...category,
    products: category.products.map(([name, price, photo]) => ({
      name, price,
      image_url: `https://images.unsplash.com/photo-${photo || category.photo}?auto=format&fit=crop&w=640&q=80`,
    })),
  }));
  return `-- GENERATED by node scripts/build-demo-category-seed.mjs
-- Opt-in DEMO data: 13 categories x 5 shops x 13 hubs = 845 shops / 8,450 products.
-- Run this WHOLE file in Supabase SQL Editor as postgres after the zone migrations.
-- Demo pins/addresses are fictional around existing hubs; no customer location is changed.
-- Rerunnable: only this seed's deterministic IDs are updated. Existing shops are untouched.
BEGIN;
SET LOCAL search_path = public, extensions, pg_temp;
SELECT pg_advisory_xact_lock(hashtext('localshore-${seedTag}'));

DO $$ BEGIN
  IF (SELECT count(*) FROM public.operational_zones WHERE is_active
      AND zone_code = ANY(ARRAY['CBE-01','CBE-02','CBE-03','CBE-04','CBE-05',
        'BLR-01','BLR-02','BLR-03','BLR-04','BLR-05','BLR-06','BLR-07','BLR-08'])) <> 13 THEN
    RAISE EXCEPTION 'Install the 13 LocalShore operational zones before running this seed.';
  END IF;
END $$;

CREATE TEMP TABLE demo_category_seed ON COMMIT DROP AS
SELECT c.*, ordinality::integer AS category_no
FROM jsonb_to_recordset(${sqlString(JSON.stringify(catalog))}::jsonb)
  WITH ORDINALITY AS c(key text, label text, photo text, products jsonb, ordinality bigint);

-- Capture and restore the exact prior notification-trigger modes. Locks last only
-- for this transaction; failure rolls back data AND trigger changes together.
CREATE TEMP TABLE demo_notification_modes ON COMMIT DROP AS
SELECT tgrelid::regclass AS relation, tgname, tgenabled
FROM pg_trigger
WHERE NOT tgisinternal AND (
  (tgrelid = 'public.products'::regclass AND tgname IN
    ('trg_notify_admins_new_product', 'trg_notify_seller_product_status')) OR
  (tgrelid = 'public.sellers'::regclass AND tgname = 'trg_notify_seller_application_status')
);
DO $$ DECLARE t record; BEGIN
  FOR t IN SELECT * FROM demo_notification_modes LOOP
    EXECUTE format('ALTER TABLE %s DISABLE TRIGGER %I', t.relation, t.tgname);
  END LOOP;
END $$;

INSERT INTO public.categories (name, slug, description, is_active)
SELECT label, key, 'LocalShore shop category', true FROM demo_category_seed
ON CONFLICT (slug) DO NOTHING;

CREATE TEMP TABLE demo_shop_seed ON COMMIT DROP AS
SELECT md5('localshore-${seedTag}-seller-' || z.zone_code || '-' || c.key || '-' || n)::uuid AS id,
  md5('localshore-${seedTag}-owner-' || z.zone_code || '-' || c.key || '-' || n)::uuid AS owner_id,
  z.zone_code, z.hub_name, z.city, z.hub_location, c.key AS category, dbcat.id AS category_id,
  c.products, n AS shop_no,
  'LocalShore Demo ' || z.zone_code || ' ' || z.hub_name || ' ' || c.label || ' Market ' || n AS shop_name,
  lower(z.zone_code) || '.' || c.key || '.' || n || '.categorydemo@localshore.test' AS email,
  'Demo Unit ' || n || ', ' || z.hub_name || ' demo market' AS address_line1,
  ST_Project(z.hub_location, (250 + n * 150)::double precision,
    radians((c.category_no * 30 + n * 72)::double precision))::geometry AS point
FROM public.operational_zones z
CROSS JOIN demo_category_seed c
CROSS JOIN generate_series(1, ${shopsPerCategory}) n
JOIN public.categories dbcat ON dbcat.slug = c.key
WHERE z.is_active AND z.zone_code = ANY(ARRAY['CBE-01','CBE-02','CBE-03','CBE-04','CBE-05',
  'BLR-01','BLR-02','BLR-03','BLR-04','BLR-05','BLR-06','BLR-07','BLR-08']);

-- Technical owners cannot sign in: no password, reserved test email, permanent ban.
INSERT INTO auth.users (instance_id, id, aud, role, email, encrypted_password,
  banned_until, raw_app_meta_data, raw_user_meta_data, created_at, updated_at)
SELECT '00000000-0000-0000-0000-000000000000'::uuid, owner_id, 'authenticated', 'authenticated',
  email, NULL, 'infinity'::timestamptz, '{"provider":"email","providers":["email"]}'::jsonb,
  jsonb_build_object('display_name', shop_name, 'demo_account', true, 'demo_seed', '${seedTag}'), now(), now()
FROM demo_shop_seed ON CONFLICT (id) DO NOTHING;

INSERT INTO public.sellers AS existing (id, user_id, business_name, full_name, email,
  business_type, status, address_line1, city, state, country, lat, lng, wizard_data)
SELECT id, owner_id, shop_name, shop_name, email, category, 'approved', address_line1, city,
  CASE WHEN city = 'Bengaluru' THEN 'Karnataka' ELSE 'Tamil Nadu' END, 'India',
  ST_Y(point), ST_X(point), jsonb_build_object('category', category, 'is_demo', true,
    'demo_seed', '${seedTag}', 'zone_code', zone_code,
    'description', 'Fictional demo shop for browsing tests. Not a real merchant.')
FROM demo_shop_seed
ON CONFLICT (id) DO UPDATE SET business_name = EXCLUDED.business_name,
  business_type = EXCLUDED.business_type, status = EXCLUDED.status,
  address_line1 = EXCLUDED.address_line1, city = EXCLUDED.city, state = EXCLUDED.state,
  lat = EXCLUDED.lat, lng = EXCLUDED.lng, wizard_data = EXCLUDED.wizard_data
WHERE existing.wizard_data->>'demo_seed' = '${seedTag}' AND existing.user_id = EXCLUDED.user_id;

INSERT INTO public.products AS existing (id, seller_id, user_id, name, sku, category, category_id,
  description, mrp, selling_price, stock, status, image_url)
SELECT md5('localshore-${seedTag}-product-' || s.id || '-' || p.name)::uuid,
  s.id, s.owner_id, p.name,
  'DEMO-CAT-' || replace(s.id::text, '-', '') || '-' || left(md5(p.name), 8),
  s.category, s.category_id,
  'Demo ' || s.category || ' listing at ' || s.shop_name || '. Illustrative stock photo; not real inventory.',
  round(p.price * 1.15, 2), p.price, 20, 'active', p.image_url
FROM demo_shop_seed s
CROSS JOIN LATERAL jsonb_to_recordset(s.products) AS p(name text, price numeric, image_url text)
ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, category = EXCLUDED.category,
  category_id = EXCLUDED.category_id, description = EXCLUDED.description,
  mrp = EXCLUDED.mrp, selling_price = EXCLUDED.selling_price, stock = EXCLUDED.stock,
  status = EXCLUDED.status, image_url = EXCLUDED.image_url
WHERE existing.seller_id = EXCLUDED.seller_id AND existing.user_id = EXCLUDED.user_id;

-- Abort atomically if ownership, category, product counts or API visibility are wrong.
DO $$ DECLARE sample record; visible_count integer; BEGIN
  IF (SELECT count(*) FROM demo_shop_seed) <> 845 THEN
    RAISE EXCEPTION 'Expected 845 demo shops';
  END IF;
  IF EXISTS (SELECT 1 FROM demo_shop_seed d JOIN public.sellers s ON s.id = d.id
      JOIN auth.users u ON u.id = s.user_id
      WHERE s.wizard_data->>'demo_seed' IS DISTINCT FROM '${seedTag}'
        OR s.business_type IS DISTINCT FROM d.category OR s.user_id <> d.owner_id
        OR u.raw_user_meta_data->>'demo_seed' IS DISTINCT FROM '${seedTag}'
        OR u.banned_until IS DISTINCT FROM 'infinity'::timestamptz
        OR NOT ST_DWithin(ST_SetSRID(ST_MakePoint(s.lng,s.lat),4326)::geography,d.hub_location,5000)) THEN
    RAISE EXCEPTION 'Demo seller identity/category/coordinates failed validation';
  END IF;
  IF EXISTS (SELECT 1 FROM demo_shop_seed d WHERE (
      SELECT count(*) FROM public.products p WHERE p.seller_id = d.id
        AND p.user_id = d.owner_id AND p.category = d.category AND p.category_id = d.category_id
        AND p.status::text IN ('active','approved') AND p.stock > 0) <> 10
      OR EXISTS (SELECT 1 FROM public.products p WHERE p.seller_id = d.id
        AND p.status::text IN ('active','approved') AND p.category IS DISTINCT FROM d.category)) THEN
    RAISE EXCEPTION 'Every demo shop must contain exactly 10 products of its own category';
  END IF;
  FOR sample IN SELECT DISTINCT zone_code, category, hub_location FROM demo_shop_seed LOOP
    SELECT count(*) INTO visible_count
    FROM public.get_customer_visible_shops(ST_Y(sample.hub_location::geometry),
      ST_X(sample.hub_location::geometry), NULL, sample.category, 100, 0) visible
    JOIN demo_shop_seed d ON d.id = visible.id
    WHERE d.zone_code = sample.zone_code AND d.category = sample.category AND visible.distance_km <= 5;
    IF visible_count < ${shopsPerCategory} THEN
      RAISE EXCEPTION 'Only % visible demo shops for % / %', visible_count, sample.zone_code, sample.category;
    END IF;
  END LOOP;
END $$;

DO $$ DECLARE t record; BEGIN
  FOR t IN SELECT * FROM demo_notification_modes LOOP
    EXECUTE format('ALTER TABLE %s %s TRIGGER %I', t.relation,
      CASE t.tgenabled WHEN 'D' THEN 'DISABLE' WHEN 'R' THEN 'ENABLE REPLICA'
        WHEN 'A' THEN 'ENABLE ALWAYS' ELSE 'ENABLE' END, t.tgname);
  END LOOP;
END $$;

SELECT d.zone_code, d.category, count(DISTINCT s.id) AS demo_shops, count(p.id) AS demo_products
FROM demo_shop_seed d JOIN public.sellers s ON s.id = d.id
JOIN public.products p ON p.seller_id = s.id AND p.status::text IN ('active','approved')
GROUP BY d.zone_code, d.category ORDER BY d.zone_code, d.category;
COMMIT;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = new URL("../supabase/seeds/category-demo-shops.sql", import.meta.url);
  fs.mkdirSync(new URL("../supabase/seeds/", import.meta.url), { recursive: true });
  fs.writeFileSync(output, buildSeedSQL());
  console.log(`Generated ${fileURLToPath(output)}`);
}
